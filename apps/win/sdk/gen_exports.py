#!/usr/bin/env python3
"""
gen_exports.py - export tables of the Windows core and the API stubs for
applications.

Every function defined as "<type> WINAPI Name(" in core/ and user/ gets a
slot: the Win16 ordinal of its module (win16.ord) or, for native
extensions, a WINN ordinal (winn.ord). Writes:

  ../core/exports.c     win_export_tables[module][ordinal] = function
  winapi_stubs.S        one thunk per function for application modules

Run after adding or removing an API function; both outputs are committed,
so building needs no Python.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MODULES = ['KERNEL', 'GDI', 'USER', 'WINN']


def implemented():
    names = set()
    for d in ('core', 'user'):
        for f in sorted(os.listdir(os.path.join(ROOT, d))):
            if not f.endswith('.c') or f == 'exports.c':
                continue
            text = open(os.path.join(ROOT, d, f)).read()
            for m in re.finditer(r'^[A-Za-z_][\w \*]*\bWINAPI\s+(\w+)\s*\(', text, re.M):
                names.add(m.group(1))
    return names


def ordinals():
    table = {}
    for line in open(os.path.join(HERE, 'win16.ord')):
        line = line.split('#')[0].split()
        if len(line) == 3 and line[2] not in table:
            table[line[2]] = (line[0], int(line[1]))
    for line in open(os.path.join(HERE, 'winn.ord')):
        line = line.split('#')[0].split()
        if len(line) == 2:
            table[line[1]] = ('WINN', int(line[0]))
    return table


def main():
    impl = implemented()
    ords = ordinals()
    missing = sorted(n for n in impl if n not in ords)
    if missing:
        sys.exit('no ordinal for: ' + ', '.join(missing) + ' (add them to winn.ord)')
    by_mod = {m: [] for m in MODULES}
    for n in sorted(impl):
        m, o = ords[n]
        by_mod[m].append((o, n))

    c = ['/* Generated by sdk/gen_exports.py - do not edit. */',
         '#include "winmod.h"', '']
    for n in sorted(impl):
        c.append('extern void %s(void);' % n)
    c.append('')
    for m in MODULES:
        items = sorted(by_mod[m])
        size = (items[-1][0] + 1) if items else 1
        c.append('static const void *const exports_%s[%d] = {' % (m.lower(), size))
        for o, n in items:
            c.append('    [%d] = (const void *)%s,' % (o, n))
        c.append('};')
        c.append('')
    c.append('const void *const *const win_export_tables[WINMOD_COUNT] = {')
    for m in MODULES:
        c.append('    exports_%s,' % m.lower())
    c.append('};')
    open(os.path.join(ROOT, 'core', 'exports.c'), 'w').write('\n'.join(c) + '\n')

    s = ['/* Generated by sdk/gen_exports.py - do not edit.',
         ' *',
         ' * Each API function of an application module jumps through',
         ' * __win_api[module][ordinal], the tables WINN.EXE hands over at start.',
         ' * Arguments in r0-r3 and on the stack are untouched (variadic calls',
         ' * included); Thumb-1 only, so the target goes through r12. */',
         '    .syntax unified', '    .thumb', '']
    for mi, m in enumerate(MODULES):
        for o, n in sorted(by_mod[m]):
            s += ['    .section .text.winapi.%s,"ax",%%progbits' % n,
                  '    .global %s' % n,
                  '    .type %s, %%function' % n,
                  '    .thumb_func',
                  '%s:' % n,
                  '    push {r0, r1}',
                  '    ldr  r0, =__win_api',
                  '    ldr  r0, [r0]',
                  '    ldr  r0, [r0, #%d]' % (mi * 4),
                  '    ldr  r1, =%d' % (o * 4),
                  '    ldr  r0, [r0, r1]',
                  '    mov  r12, r0',
                  '    pop  {r0, r1}',
                  '    bx   r12',
                  '    .ltorg',
                  '    .size %s, .-%s' % (n, n),
                  '']
    open(os.path.join(HERE, 'winapi_stubs.S'), 'w').write('\n'.join(s))
    print('%d functions: %s' % (len(impl), ', '.join('%s %d' % (m, len(by_mod[m])) for m in MODULES)))


main()
